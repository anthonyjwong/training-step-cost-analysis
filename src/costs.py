@dataclass
class EpochCost:
    env: str
    machine: str
    model_name: str
    max_throughput_batch_size: int
    price_per_hour: float
    spot_price_per_hour: float
    hours_per_epoch: float
    cost: float
    spot_cost: float

    @classmethod
    def from_benchmark(cls, b: BenchSummary, price: Price) -> Self:
        hours = IMAGENET_IMAGES / b.images_per_second / 3600
        return cls(
            b.env,
            price.name,
            b.model_name,
            b.batch_size,
            price.on_demand,
            price.spot,
            hours,
            hours * price.on_demand,
            hours * price.spot,
        )


@dataclass
class LocalVsCloudCost:
    local: str
    cloud: str
    model_name: str
    cloud_to_local_speedup: float
    cloud_to_local_cost_ratio: float
    cloud_to_local_spot_cost_ratio: float
    price_per_hour_saved: float | None
    spot_price_per_hour_saved: float | None

    @classmethod
    def from_costs(cls, local: EpochCost, cloud: EpochCost) -> Self:
        saved = local.hours_per_epoch - cloud.hours_per_epoch
        return cls(
            local.env,
            cloud.env,
            local.model_name,
            local.hours_per_epoch / cloud.hours_per_epoch,
            cloud.cost / local.cost,
            cloud.spot_cost / local.spot_cost,
            cloud.cost / saved if saved > 0 else None,
            cloud.spot_cost / saved if saved > 0 else None,
        )


@dataclass
class CloudVsCloudCost:
    small_cloud: str
    large_cloud: str
    model_name: str
    large_to_small_speedup: float
    large_to_small_cost_ratio: float
    large_to_small_spot_cost_ratio: float
    price_per_hour_saved: float | None
    spot_price_per_hour_saved: float | None

    @classmethod
    def from_costs(cls, small: EpochCost, large: EpochCost) -> Self:
        saved = small.hours_per_epoch - large.hours_per_epoch
        return cls(
            small.env,
            large.env,
            small.model_name,
            small.hours_per_epoch / large.hours_per_epoch,
            large.cost / small.cost,
            large.spot_cost / small.spot_cost,
            (large.cost - small.cost) / saved if saved > 0 else None,
            (large.spot_cost - small.spot_cost) / saved if saved > 0 else None,
        )


@dataclass
class GpuBuyOrRentCutoff:
    bought_gpu: str
    rented_gpu: str
    rented_instance_name: str
    model_name: str
    bought_price: float
    bought_life_years: float
    rented_hours_per_epoch: float
    rent_per_epoch: float
    spot_rent_per_epoch: float
    bought_to_rented_speedup: float
    cutoff_epochs: float
    spot_cutoff_epochs: float
    cutoff_hours_per_day: float
    spot_cutoff_hours_per_day: float

    @classmethod
    def from_cost(
        cls,
        bought: AmortizedGpu,
        rented_gpu: Gpu,
        rented: EpochCost,
        arithmetic_intensity: float,
    ) -> Self:
        speedup = bought.gpu.get_speedup_over(rented_gpu, arithmetic_intensity)
        bought_hours_per_epoch = rented.hours_per_epoch / speedup
        cutoff_epochs = bought.get_cutoff_epochs(rented.cost)
        spot_cutoff_epochs = bought.get_cutoff_epochs(rented.spot_cost)

        return cls(
            bought.gpu.name,
            rented_gpu.name,
            rented.machine,
            rented.model_name,
            bought.price,
            bought.life_years,
            rented.hours_per_epoch,
            rented.cost,
            rented.spot_cost,
            speedup,
            cutoff_epochs,
            spot_cutoff_epochs,
            bought.get_hours_per_day(cutoff_epochs, bought_hours_per_epoch),
            bought.get_hours_per_day(spot_cutoff_epochs, bought_hours_per_epoch),
        )

    @classmethod
    def from_csv_row(cls, row: dict[str, str]) -> Self:
        return cls(
            bought_gpu=row["bought_gpu"],
            rented_gpu=row["rented_gpu"],
            rented_instance_name=row["rented_instance_name"],
            model_name=row["model_name"],
            bought_price=float(row["bought_price"]),
            bought_life_years=float(row["bought_life_years"]),
            rented_hours_per_epoch=float(row["rented_hours_per_epoch"]),
            rent_per_epoch=float(row["rent_per_epoch"]),
            spot_rent_per_epoch=float(row["spot_rent_per_epoch"]),
            bought_to_rented_speedup=float(row["bought_to_rented_speedup"]),
            cutoff_epochs=float(row["cutoff_epochs"]),
            spot_cutoff_epochs=float(row["spot_cutoff_epochs"]),
            cutoff_hours_per_day=float(row["cutoff_hours_per_day"]),
            spot_cutoff_hours_per_day=float(row["spot_cutoff_hours_per_day"]),
        )


def get_max_throughput(
    benchmarks: list[BenchSummary],
) -> dict[tuple[str, str], BenchSummary]:
    max_per_key: dict[tuple[str, str], BenchSummary] = {}
    for b in benchmarks:
        key = (b.env, b.model_name)
        max_throughput = max_per_key.setdefault(key, b)
        if b.images_per_second > max_throughput.images_per_second:
            max_per_key[key] = b

    return max_per_key


def write_output(
    costs: list[EpochCost],
    local_vs_cloud: list[LocalVsCloudCost],
    cloud_vs_cloud: list[CloudVsCloudCost],
    cutoffs: list[GpuBuyOrRentCutoff],
):
    def get_saved_text(on_demand: float | None, spot: float | None) -> str:
        if on_demand is None or spot is None:
            return ""
        return f"  ${on_demand:.2f}/h saved (spot ${spot:.2f})"

    write_csv("out/costs/costs.csv", costs)
    write_csv("out/costs/local_vs_cloud.csv", local_vs_cloud)
    write_csv("out/costs/cloud_vs_cloud.csv", cloud_vs_cloud)
    write_csv("out/costs/gpu_buy_or_rent_cutoff.csv", cutoffs)

    for c in costs:
        print(
            f"{c.env:14} {c.model_name:13} b{c.max_throughput_batch_size:<3}"
            + f" {c.hours_per_epoch:7.2f} h/epoch"
            + f"  ${c.cost:7.2f} (spot ${c.spot_cost:.2f})"
        )
    for c in local_vs_cloud:
        print(
            f"{c.cloud} vs {c.local} {c.model_name}:"
            + f" x{c.cloud_to_local_speedup:.2f} speed,"
            + f" x{c.cloud_to_local_cost_ratio:.2f} cost"
            + f" (spot x{c.cloud_to_local_spot_cost_ratio:.2f})"
            + get_saved_text(c.price_per_hour_saved, c.spot_price_per_hour_saved)
        )
    for c in cloud_vs_cloud:
        print(
            f"{c.large_cloud} vs {c.small_cloud} {c.model_name}:"
            + f" x{c.large_to_small_speedup:.2f} speed,"
            + f" x{c.large_to_small_cost_ratio:.2f} cost"
            + f" (spot x{c.large_to_small_spot_cost_ratio:.2f})"
            + get_saved_text(c.price_per_hour_saved, c.spot_price_per_hour_saved)
        )
    for c in cutoffs:
        print(
            f"{c.bought_gpu} vs {c.rented_instance_name} ({c.rented_gpu}) {c.model_name}:"
            + f" speedup {c.bought_to_rented_speedup:.2f}, buy after"
            + f" {c.cutoff_epochs:,.0f} epochs ({c.cutoff_hours_per_day:.2f} h/day), spot"
            + f" {c.spot_cutoff_epochs:,.0f} ({c.spot_cutoff_hours_per_day:.2f} h/day)"
        )

    print(
        "wrote out/costs/costs.csv, local_vs_cloud.csv, cloud_vs_cloud.csv,"
        + " gpu_buy_or_rent_cutoff.csv"
    )


def main():
    benchmarks = [
        BenchSummary.from_csv_row(row)
        for row in read_stage_csv(SUMMARY_BENCH, "summarize")
    ]
    cloud_prices = get_cloud_instance_prices()
    max_throughput_benchmarks = get_max_throughput(
        [b for b in benchmarks if b.env in cloud_prices]
    )
    costs = {
        key: EpochCost.from_benchmark(b, cloud_prices[key[0]])
        for key, b in sorted(
            max_throughput_benchmarks.items(),
            key=lambda kv: (
                list(cloud_prices).index(kv[0][0]),
                MODELS.index(kv[0][1]),
            ),
        )
    }

    local_vs_cloud = [
        LocalVsCloudCost.from_costs(costs[(local, m)], costs[(cloud, m)])
        for local, cloud in LOCAL_VS_CLOUD
        for m in MODELS
        if (local, m) in costs and (cloud, m) in costs
    ]
    cloud_vs_cloud = [
        CloudVsCloudCost.from_costs(costs[(small, m)], costs[(large, m)])
        for small, large in CLOUD_VS_CLOUD
        for m in MODELS
        if (small, m) in costs and (large, m) in costs
    ]

    rented_gpus = {
        env: price.gpu for env, price in cloud_prices.items() if price.gpu is not None
    }
    cutoffs = [
        GpuBuyOrRentCutoff.from_cost(
            AMORTIZED_RTX_5080,
            rented_gpu,
            costs[(env, m)],
            max_throughput_benchmarks[(env, m)].arithmetic_intensity,
        )
        for env, rented_gpu in rented_gpus.items()
        for m in MODELS
        if (env, m) in costs
    ]

    write_output(list(costs.values()), local_vs_cloud, cloud_vs_cloud, cutoffs)


if __name__ == "__main__":
    main()
