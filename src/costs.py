L4 = Gpu(name="L4", peak_gflops=30300, peak_gbs=300)


@dataclass
class Price:
    """GCP bills per vCPU, per GB of memory, and per GPU, per hour; rates dynamically generated by `prices.py`"""

    name: str
    on_demand: float
    spot: float
    gpu: Gpu | None = None

    @classmethod
    def from_n2(
        cls, name: str, num_vcpus: int, memory_gb_size: int, rates: dict[GcpSku, float]
    ) -> Self:
        return cls(
            name,
            num_vcpus * rates[GcpSku.N2_CORE] + memory_gb_size * rates[GcpSku.N2_RAM],
            num_vcpus * rates[GcpSku.N2_SPOT_CORE]
            + memory_gb_size * rates[GcpSku.N2_SPOT_RAM],
        )

    @classmethod
    def from_g2(
        cls,
        name: str,
        num_vcpus: int,
        memory_gb_size: int,
        num_gpus: int,
        rates: dict[GcpSku, float],
    ) -> Self:
        return cls(
            name,
            num_vcpus * rates[GcpSku.G2_CORE]
            + memory_gb_size * rates[GcpSku.G2_RAM]
            + num_gpus * rates[GcpSku.L4],
            num_vcpus * rates[GcpSku.G2_SPOT_CORE]
            + memory_gb_size * rates[GcpSku.G2_SPOT_RAM]
            + num_gpus * rates[GcpSku.L4_SPOT],
            L4,
        )


