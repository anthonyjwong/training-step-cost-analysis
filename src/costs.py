@dataclass
class Gpu:
    name: str
    peak_gflops: float
    peak_gbs: float

    def get_attainable_gflops(self, arithmetic_intensity: float) -> float:
        # roofline formula
        return min(arithmetic_intensity * self.peak_gbs, self.peak_gflops)

    def get_speedup_over(self, other: "Gpu", arithmetic_intensity: float) -> float:
        return self.get_attainable_gflops(
            arithmetic_intensity
        ) / other.get_attainable_gflops(arithmetic_intensity)


@dataclass
class AmortizedGpu:
    gpu: Gpu
    price: float
    life_years: float

    def get_cutoff_epochs(self, rent_per_epoch: float) -> float:
        return self.price / rent_per_epoch

    def get_hours_per_day(self, epochs: float, hours_per_epoch: float) -> float:
        return epochs * hours_per_epoch / (self.life_years * 365)


